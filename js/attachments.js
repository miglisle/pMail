/* pMail — attachment rendering, preview and (for demo mail) on-the-fly file generation */
(function (PM) {
  'use strict';
  const U = PM.util, UI = PM.ui;
  const AT = (PM.att = {});
  const urlCache = new Map();

  AT.kind = (a) => {
    const m = (a.mime || '').toLowerCase(), n = a.name.toLowerCase();
    if (m.startsWith('image/') || /\.(png|jpe?g|gif|webp|svg)$/.test(n)) return 'image';
    if (m === 'application/pdf' || n.endsWith('.pdf')) return 'pdf';
    if (m === 'text/csv' || n.endsWith('.csv')) return 'sheet';
    if (m === 'text/calendar' || n.endsWith('.ics')) return 'calendar';
    if (m.startsWith('text/') || /\.(txt|md|log|json)$/.test(n)) return 'text';
    if (/\.(zip|rar|7z|gz)$/.test(n)) return 'zip';
    if (/\.(docx?|odt|rtf)$/.test(n)) return 'doc';
    if (/\.(xlsx?|ods)$/.test(n)) return 'sheet';
    if (/\.(pptx?|odp|key)$/.test(n)) return 'slides';
    if (m.startsWith('audio/')) return 'audio';
    if (m.startsWith('video/')) return 'video';
    return 'file';
  };
  const KIND_STYLE = {
    pdf: ['#db4437', 'PDF'], sheet: ['#0f9d58', 'CSV'], calendar: ['#4285f4', 'ICS'], text: ['#5f6368', 'TXT'],
    zip: ['#795548', 'ZIP'], doc: ['#4285f4', 'DOC'], slides: ['#f4b400', 'PPT'], audio: ['#9c27b0', '♪'], video: ['#e53935', '▶'], file: ['#9e9e9e', 'FILE'], image: ['#ab47bc', 'IMG'],
  };
  AT.badge = (a) => {
    const k = AT.kind(a);
    const [c, t] = KIND_STYLE[k] || KIND_STYLE.file;
    const ext = (a.name.split('.').pop() || t).toUpperCase().slice(0, 4);
    return `<span class="att-badge" style="background:${c}">${U.esc(k === 'image' ? 'IMG' : ext)}</span>`;
  };

  /* ---------- generated demo files ---------- */
  function hash(s) { let h = 2166136261; for (const c of s) { h ^= c.charCodeAt(0); h = Math.imul(h, 16777619); } return h >>> 0; }

  function makeImage(a) {
    const W = 960, H = 640;
    const cv = document.createElement('canvas'); cv.width = W; cv.height = H;
    const x = cv.getContext('2d');
    const h = hash(a.name);
    const n = a.name.toLowerCase();
    if (/mock|sketch|concept|logo|review/.test(n)) {
      x.fillStyle = '#f5f6f8'; x.fillRect(0, 0, W, H);
      const hue = h % 360;
      for (let i = 0; i < 3; i++) {
        const px = 60 + i * 300;
        x.fillStyle = '#fff'; x.strokeStyle = '#d0d4da'; x.lineWidth = 2;
        x.fillRect(px, 70, 240, 480); x.strokeRect(px, 70, 240, 480);
        x.fillStyle = `hsl(${hue},55%,55%)`; x.fillRect(px, 70, 240, 54);
        x.fillStyle = '#e3e6ea';
        for (let j = 0; j < 6; j++) x.fillRect(px + 20, 150 + j * 52, 200 - (j % 3) * 40, 24);
        x.fillStyle = `hsl(${(hue + 30) % 360},60%,50%)`; x.fillRect(px + 20, 480, 200, 44);
        x.fillStyle = '#fff'; x.font = 'bold 18px Arial'; x.fillText(n.includes('logo') ? `Concept ${i + 1}` : `Step ${i + 1}`, px + 22, 104);
      }
      x.fillStyle = '#555'; x.font = '20px Arial'; x.fillText(a.name, 60, 610);
    } else {
      const hue = h % 360;
      const g = x.createLinearGradient(0, 0, 0, H);
      g.addColorStop(0, `hsl(${(hue + 20) % 360},70%,62%)`);
      g.addColorStop(0.55, `hsl(${(hue + 340) % 360},75%,72%)`);
      g.addColorStop(1, `hsl(${(hue + 200) % 360},45%,30%)`);
      x.fillStyle = g; x.fillRect(0, 0, W, H);
      x.fillStyle = 'rgba(255,240,200,.9)'; x.beginPath(); x.arc(W * 0.68, H * 0.42, 70, 0, Math.PI * 2); x.fill();
      for (let k = 0; k < 3; k++) {
        x.fillStyle = `rgba(20,30,50,${0.35 + k * 0.2})`;
        x.beginPath(); x.moveTo(0, H);
        for (let i = 0; i <= 12; i++) x.lineTo((W / 12) * i, H * (0.55 + k * 0.1) + Math.sin(i * 1.3 + h + k * 2) * 40);
        x.lineTo(W, H); x.fill();
      }
      x.fillStyle = 'rgba(255,255,255,.15)';
      x.fillRect(0, H * 0.82, W, H * 0.18);
    }
    return cv.toDataURL(n.endsWith('.png') ? 'image/png' : 'image/jpeg', 0.86);
  }

  function pdfEsc(s) { return String(s).replace(/[\\()]/g, (c) => '\\' + c).replace(/[^\x20-\x7e]/g, ''); }
  function makePdf(title, lines) {
    let content = `BT /F2 22 Tf 72 712 Td (${pdfEsc(title)}) Tj ET\n0.85 0.29 0.22 RG 2 w 72 700 m 540 700 l S\nBT /F1 12 Tf 72 676 Td 16 TL\n`;
    lines.forEach((l) => { content += `(${pdfEsc(l)}) Tj T*\n`; });
    content += 'ET\nBT /F1 9 Tf 0.5 g 72 60 Td (Generated by pMail demo mailbox) Tj ET';
    const objs = [
      '<< /Type /Catalog /Pages 2 0 R >>',
      '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
      '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 4 0 R /Resources << /Font << /F1 5 0 R /F2 6 0 R >> >> >>',
      `<< /Length ${content.length} >>\nstream\n${content}\nendstream`,
      '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
      '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>',
    ];
    let out = '%PDF-1.4\n';
    const offs = [];
    objs.forEach((o, i) => { offs.push(out.length); out += `${i + 1} 0 obj\n${o}\nendobj\n`; });
    const xref = out.length;
    out += `xref\n0 ${objs.length + 1}\n0000000000 65535 f \n` + offs.map((o) => String(o).padStart(10, '0') + ' 00000 n \n').join('');
    out += `trailer\n<< /Size ${objs.length + 1} /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF`;
    return new Blob([out], { type: 'application/pdf' });
  }

  function pdfLines(name, msg) {
    const n = name.toLowerCase();
    if (n.includes('roadmap')) return ['Q4 Roadmap - DRAFT', '', '1. Onboarding refresh', '   Goal: cut time-to-first-value in half', '   Owner: Design + Growth', '', '2. Offline mode (read-only for Q4)', '   Goal: read mail without a connection', '   Owner: Platform', '', '3. Performance', '   Goal: sub-second list rendering for large accounts', '   Owner: Platform', '', 'Open questions', ' - Staffing for offline drafts (moved to Q1)', ' - Research window for onboarding (2 weeks)'];
    if (n.includes('lease')) return ['Lease Renewal Offer - Unit 3B', '', 'Tenant: Pat Morgan', 'Property: 1420 Alder St, Unit 3B', '', 'Option A: 12-month term - rent unchanged', 'Option B: 6-month term - 2% increase', '', 'Please sign and return by December 31.', '', 'Greenleaf Property Management'];
    if (n.includes('itinerary')) return ['Brightwing Airlines - Itinerary', '', 'Confirmation: K7Q2XM', 'Passenger: PAT MORGAN', '', 'BW 412  Dec 19  SFO 7:05 AM  ->  BOS 3:41 PM  Seat 14A', 'BW 419  Dec 27  BOS 5:30 PM  ->  SFO 9:02 PM  Seat 12C', '', 'Baggage: 1 carry-on, 1 personal item included.'];
    const text = U.textOf(msg ? msg.html : '').slice(0, 900);
    const words = text.split(' ');
    const lines = [];
    let cur = '';
    words.forEach((w) => { if ((cur + ' ' + w).length > 82) { lines.push(cur); cur = w; } else cur = cur ? cur + ' ' + w : w; });
    if (cur) lines.push(cur);
    return lines.length ? lines : ['This is a sample document attached to a demo message.'];
  }

  function textFor(a, msg) {
    const n = a.name.toLowerCase();
    if (n.endsWith('.csv')) return 'Initiative,Engineers,Weeks,Confidence\nOnboarding refresh,2,5,Medium\nOffline mode (read-only),2,8,Low\nPerformance,1,4,High\nOffline drafts (Q1),2,6,Low\n';
    if (n.endsWith('.ics')) {
      const d = new Date(Date.now() + 6 * 864e5);
      const ymd = d.toISOString().slice(0, 10).replace(/-/g, '');
      return `BEGIN:VCALENDAR\r\nVERSION:2.0\r\nPRODID:-//pMail//Demo//EN\r\nBEGIN:VEVENT\r\nUID:${a.id}@pmail\r\nDTSTART:${ymd}T220000Z\r\nDTEND:${ymd}T233000Z\r\nSUMMARY:${(msg && msg.subject) || 'Event'}\r\nEND:VEVENT\r\nEND:VCALENDAR\r\n`;
    }
    return U.textOf(msg ? msg.html : '') || 'Sample attachment';
  }

  /* Resolve a downloadable URL for an attachment */
  AT.url = function (a, msg) {
    if (a.data) return a.data;
    if (urlCache.has(a.id)) return urlCache.get(a.id);
    const k = AT.kind(a);
    let url;
    if (k === 'image') url = makeImage(a);
    else if (k === 'pdf') url = URL.createObjectURL(makePdf(a.name.replace(/\.pdf$/i, '').replace(/[-_]/g, ' '), pdfLines(a.name, msg)));
    else url = URL.createObjectURL(new Blob([textFor(a, msg)], { type: a.mime || 'text/plain' }));
    urlCache.set(a.id, url);
    return url;
  };

  AT.thumb = function (a, msg) {
    if (AT.kind(a) === 'image') return `<img src="${AT.url(a, msg)}" alt="">`;
    const k = AT.kind(a);
    const [c] = KIND_STYLE[k] || KIND_STYLE.file;
    return `<div class="att-doc"><div class="att-page"><span></span><span></span><span></span><span></span><span></span></div><span class="att-type" style="background:${c}">${U.esc((a.name.split('.').pop() || '').toUpperCase().slice(0, 4))}</span></div>`;
  };

  AT.download = (a, msg) => U.download(a.name, AT.url(a, msg));

  /* ---------- preview viewer ---------- */
  AT.preview = function (a, msg, list) {
    list = list || [a];
    let i = Math.max(0, list.indexOf(a));
    const ov = U.h(`<div class="viewer" tabindex="-1"><div class="vw-bar"><span class="vw-name"></span><span class="vw-r">
      <button class="vw-btn" data-v="print" data-tip="Print">${PM.icon('print', 22)}</button>
      <button class="vw-btn" data-v="dl" data-tip="Download">${PM.icon('download', 22)}</button>
      <button class="vw-btn" data-v="close" data-tip="Close">${PM.icon('close', 22)}</button></span></div>
      <div class="vw-body"></div>
      <button class="vw-nav vw-prev" data-v="prev">${PM.icon('left', 40)}</button><button class="vw-nav vw-next" data-v="next">${PM.icon('right', 40)}</button></div>`);
    const body = U.$('.vw-body', ov);
    const show = () => {
      const cur = list[i];
      U.$('.vw-name', ov).innerHTML = `${AT.badge(cur)} ${U.esc(cur.name)}`;
      const k = AT.kind(cur), url = AT.url(cur, msg);
      if (k === 'image') body.innerHTML = `<img class="vw-img" src="${url}" alt="${U.esc(cur.name)}">`;
      else if (k === 'pdf') body.innerHTML = `<iframe class="vw-pdf" src="${url}" title="${U.esc(cur.name)}"></iframe>`;
      else if (['text', 'sheet', 'calendar'].includes(k) && !cur.data) body.innerHTML = `<pre class="vw-text">${U.esc(textFor(cur, msg))}</pre>`;
      else if (['text', 'sheet', 'calendar'].includes(k) && cur.data) {
        body.innerHTML = '<pre class="vw-text">Loading…</pre>';
        fetch(cur.data).then((r) => r.text()).then((t) => { body.innerHTML = `<pre class="vw-text">${U.esc(t.slice(0, 200000))}</pre>`; }).catch(() => {});
      } else body.innerHTML = `<div class="vw-none"><div class="vw-none-ic">${AT.badge(cur)}</div><div>No preview available</div><button class="jb jb-blue" data-v="dl">Download</button></div>`;
      U.$('.vw-prev', ov).hidden = i === 0;
      U.$('.vw-next', ov).hidden = i === list.length - 1;
    };
    const close = () => { ov.remove(); document.removeEventListener('keydown', key, true); };
    const key = (e) => {
      if (e.key === 'Escape') { e.stopPropagation(); e.preventDefault(); close(); }
      else if (e.key === 'ArrowLeft' && i > 0) { i--; show(); }
      else if (e.key === 'ArrowRight' && i < list.length - 1) { i++; show(); }
    };
    ov.addEventListener('click', (e) => {
      const b = e.target.closest('[data-v]');
      if (!b) { if (e.target === ov || e.target === body) close(); return; }
      const v = b.dataset.v;
      if (v === 'close') close();
      else if (v === 'dl') AT.download(list[i], msg);
      else if (v === 'prev' && i > 0) { i--; show(); }
      else if (v === 'next' && i < list.length - 1) { i++; show(); }
      else if (v === 'print') {
        const w = window.open('', '_blank');
        if (!w) return;
        const k = AT.kind(list[i]);
        w.document.write(k === 'image' ? `<img src="${AT.url(list[i], msg)}" style="max-width:100%">` : `<pre>${U.esc(textFor(list[i], msg))}</pre>`);
        w.document.close(); w.focus(); w.print();
      }
    });
    document.addEventListener('keydown', key, true);
    document.body.appendChild(ov);
    show();
    ov.focus();
  };

  /* Read a File for attaching. Resolves {id,name,size,mime,data} */
  AT.MAX = 2 * 1024 * 1024;
  AT.readFile = (file) => new Promise((res, rej) => {
    if (file.size > AT.MAX) { rej(new Error(`The file "${file.name}" exceeds the ${U.fileSize(AT.MAX)} attachment limit of this demo (pMail keeps everything in your browser's storage).`)); return; }
    const r = new FileReader();
    r.onload = () => res({ id: U.uid(8), name: file.name, size: file.size, mime: file.type || 'application/octet-stream', data: r.result });
    r.onerror = () => rej(new Error('Could not read ' + file.name));
    r.readAsDataURL(file);
  });
})(window.PM);
